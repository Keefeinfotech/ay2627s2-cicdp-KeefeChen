import { afterEach, describe, expect, it, vi } from "vitest";
import { createGuardrails, generateSync } from "otplib";
import {
  generateTotpSecret,
  generateTotpUri,
  verifyTotpCode,
} from "../../src/shared/utils/totp.util";

const FIXED_EPOCH = 1704067200; // 2024-01-01T00:00:00Z
const LEGACY_SECRET = "FUJFQTJENRNGQX32"; // 10-byte v12-style secret
const LEGACY_GUARDRAILS = createGuardrails({
  MIN_SECRET_BYTES: 10,
});

afterEach(() => {
  vi.useRealTimers();
});

describe("totp utility (otplib v13 migration)", () => {
  it("generates base32 secrets that can be verified", () => {
    const secret = generateTotpSecret();

    expect(secret).toMatch(/^[A-Z2-7]+$/);
    expect(verifyTotpCode(secret, generateSync({ secret }))).toBe(true);
  });

  it("builds an otpauth URI with the issuer and account label", () => {
    const secret = generateTotpSecret();
    const uri = generateTotpUri("user@example.com", secret);

    expect(uri).toContain("otpauth://totp/");
    expect(uri).toContain("issuer=Auxilia");
    expect(uri).toContain("user%40example.com");
    expect(uri).toContain(`secret=${secret}`);
  });

  it("keeps the one-step verification window from otplib v12", () => {
    vi.useFakeTimers();
    vi.setSystemTime(FIXED_EPOCH * 1000);
    const secret = generateTotpSecret();
    const token = generateSync({ secret, epoch: FIXED_EPOCH });

    expect(
      verifyTotpCode(secret, generateSync({ secret, epoch: FIXED_EPOCH - 30 })),
    ).toBe(true);
    expect(
      verifyTotpCode(secret, generateSync({ secret, epoch: FIXED_EPOCH + 30 })),
    ).toBe(true);
    expect(verifyTotpCode(secret, token)).toBe(true);
    expect(
      verifyTotpCode(secret, generateSync({ secret, epoch: FIXED_EPOCH - 60 })),
    ).toBe(false);
    expect(
      verifyTotpCode(secret, generateSync({ secret, epoch: FIXED_EPOCH + 60 })),
    ).toBe(false);
  });

  it("still verifies secrets generated by otplib v12", () => {
    vi.useFakeTimers();
    vi.setSystemTime(FIXED_EPOCH * 1000);
    const token = generateSync({
      secret: LEGACY_SECRET,
      epoch: FIXED_EPOCH,
      guardrails: LEGACY_GUARDRAILS,
    });

    expect(verifyTotpCode(LEGACY_SECRET, token)).toBe(true);
  });

  it("rejects malformed codes and secrets without throwing", () => {
    expect(verifyTotpCode(generateTotpSecret(), "12ab56")).toBe(false);
    expect(verifyTotpCode("not-base32!", "123456")).toBe(false);
  });
});
